#!/usr/bin/env bash
# Writes the AUR `sona-bin` PKGBUILD and .SRCINFO for a release: pkgver from
# VERSION, the checksum of that release's Arch package (the asset the
# PKGBUILD downloads).
#
#   build/linux/arch/update.sh <sona-<ver>-1-x86_64.pkg.tar.zst> [out-dir]
#
# out-dir defaults to build/linux/arch. The release workflow runs this on the
# package it publishes and attaches both files to the GitHub release; the
# AUR maintainer copies them into the AUR repo (nothing here pushes to AUR).
set -euo pipefail

root=$(cd "$(dirname "$0")/../../.." && pwd)
pkg=$1
out=${2:-$root/build/linux/arch}
pkgver=$(<"$root/VERSION")
pkgrel=1

[[ $(basename "$pkg") == "sona-$pkgver-1-x86_64.pkg.tar.zst" ]] ||
  { echo "update.sh: $pkg is not the $pkgver Arch package" >&2; exit 1; }
sha=$(sha256sum "$pkg" | cut -d' ' -f1)
mkdir -p "$out"

# Keep depends in step with the archlinux override in build/linux/nfpm/nfpm.yaml.
depends=(gtk4 webkitgtk-6.0 gstreamer gst-plugins-base gst-plugins-good gst-plugins-bad gst-libav)
optdepends=(
  "google-chrome: Widevine CDM for full-track playback (Sona uses the installed one; never bundled)"
  "chromium: Widevine CDM via its component updater, as an alternative to Google Chrome"
  "gst-plugin-pipewire: native PipeWire audio output (pulsesink otherwise)"
)
source_url="https://github.com/coredev-uk/sona-go/releases/download/v\${pkgver}/sona-\${pkgver}-1-x86_64.pkg.tar.zst"

q() { printf "'%s' " "$@"; }

cat >"$out/PKGBUILD" <<EOF
# Maintainer: Core <core@coredev.uk>
#
# Generated by build/linux/arch/update.sh in github.com/coredev-uk/sona-go;
# edit that script, not this file.
#
# Repackages the Arch package from Sona's GitHub release. Sona never bundles
# or downloads a Widevine CDM: it uses the one from the user's own Google
# Chrome (or Chromium) install at runtime.

pkgname=sona-bin
pkgver=$pkgver
pkgrel=$pkgrel
pkgdesc='Apple Music for the Linux desktop'
arch=('x86_64')
url='https://github.com/coredev-uk/sona-go'
license=('AGPL-3.0-only' 'BSD-3-Clause')
depends=($(q "${depends[@]}" | sed 's/ $//'))
optdepends=(
$(printf "  '%s'\n" "${optdepends[@]}")
)
provides=('sona')
conflicts=('sona')
# The release binary is already stripped; there is nothing to split out.
options=('!strip' '!debug')
source=("$source_url")
noextract=("sona-\${pkgver}-1-x86_64.pkg.tar.zst")
sha256sums=('$sha')

package() {
  bsdtar -xf "sona-\${pkgver}-1-x86_64.pkg.tar.zst" -C "\$pkgdir" usr
  install -Dm644 "\$pkgdir/usr/share/doc/sona/LICENSE.chromium" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE.chromium"
}
EOF

{
  echo "pkgbase = sona-bin"
  printf '\tpkgdesc = %s\n' 'Apple Music for the Linux desktop'
  printf '\tpkgver = %s\n' "$pkgver"
  printf '\tpkgrel = %s\n' "$pkgrel"
  printf '\turl = %s\n' 'https://github.com/coredev-uk/sona-go'
  printf '\tarch = x86_64\n'
  printf '\tlicense = %s\n' AGPL-3.0-only BSD-3-Clause
  printf '\tdepends = %s\n' "${depends[@]}"
  printf '\toptdepends = %s\n' "${optdepends[@]}"
  printf '\tprovides = sona\n'
  printf '\tconflicts = sona\n'
  printf '\tnoextract = sona-%s-1-x86_64.pkg.tar.zst\n' "$pkgver"
  printf '\toptions = %s\n' '!strip' '!debug'
  printf '\tsource = %s\n' "https://github.com/coredev-uk/sona-go/releases/download/v$pkgver/sona-$pkgver-1-x86_64.pkg.tar.zst"
  printf '\tsha256sums = %s\n' "$sha"
  echo
  echo "pkgname = sona-bin"
} >"$out/.SRCINFO"

echo "update.sh: wrote $out/PKGBUILD and $out/.SRCINFO for $pkgver ($sha)"
