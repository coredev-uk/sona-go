package cli

import (
	"fmt"
	"io"
	"strings"
)

// writeCompletion prints the completion script for shell (bash, zsh or
// fish), generated from the command table.
func writeCompletion(w io.Writer, shell string) error {
	var b strings.Builder
	switch shell {
	case "bash":
		bashCompletion(&b)
	case "zsh":
		zshCompletion(&b)
	case "fish":
		fishCompletion(&b)
	default:
		return Usage(msgBadChoice, "completion", shell, strings.Join(shells, ", "))
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// shellQuote quotes s for a POSIX shell (and zsh and fish) as one word.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// fishQuote quotes s for fish, where '\” doesn't work.
func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

func names() []string {
	out := make([]string, len(commands))
	for i, c := range commands {
		out[i] = c.name
	}
	return out
}

// words are what may follow the command: its first argument's values and
// its options.
func (c *command) words() []string {
	out := append([]string(nil), c.choices...)
	for _, f := range c.flags {
		out = append(out, "--"+f.name)
	}
	return append(out, "--help")
}

func bashCompletion(b *strings.Builder) {
	b.WriteString("# bash completion for sona, generated by `sona completion bash`.\n")
	b.WriteString("_sona() {\n")
	b.WriteString("\tlocal cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}\n")
	b.WriteString("\tif ((COMP_CWORD == 1)); then\n")
	fmt.Fprintf(b, "\t\tmapfile -t COMPREPLY < <(compgen -W %s -- \"$cur\")\n", shellQuote(strings.Join(names(), " ")))
	b.WriteString("\t\treturn\n\tfi\n")
	b.WriteString("\tcase ${COMP_WORDS[1]} in\n")
	for _, c := range commands {
		fmt.Fprintf(b, "\t%s)\n", c.name)
		var values []string
		for _, f := range c.flags {
			if f.value != "" {
				values = append(values, fmt.Sprintf("\t\t--%s) mapfile -t COMPREPLY < <(compgen -W %s -- \"$cur\"); return ;;\n",
					f.name, shellQuote(strings.Join(f.choices, " "))))
			}
		}
		if len(values) > 0 {
			b.WriteString("\t\tcase $prev in\n")
			for _, v := range values {
				b.WriteString(v)
			}
			b.WriteString("\t\tesac\n")
		}
		fmt.Fprintf(b, "\t\tmapfile -t COMPREPLY < <(compgen -W %s -- \"$cur\")\n\t\t;;\n", shellQuote(strings.Join(c.words(), " ")))
	}
	b.WriteString("\tesac\n}\ncomplete -F _sona sona\n")
}

// zshDesc escapes a description for _arguments' [...] and _describe.
func zshDesc(s string) string {
	return strings.NewReplacer(`\`, `\\`, `[`, `\[`, `]`, `\]`, `:`, `\:`).Replace(s)
}

func zshCompletion(b *strings.Builder) {
	b.WriteString("#compdef sona\n# zsh completion for sona, generated by `sona completion zsh`.\n")
	b.WriteString("_sona() {\n\tlocal -a commands\n\tcommands=(\n")
	for _, c := range commands {
		fmt.Fprintf(b, "\t\t%s\n", shellQuote(c.name+":"+zshDesc(c.summary)))
	}
	b.WriteString("\t)\n\tif ((CURRENT == 2)); then\n\t\t_describe -t commands 'sona command' commands\n\t\treturn\n\tfi\n")
	b.WriteString("\tshift words\n\t((CURRENT--))\n\tcase $words[1] in\n")
	for _, c := range commands {
		fmt.Fprintf(b, "\t%s)\n\t\t_arguments", c.name)
		for _, f := range c.flags {
			spec := "--" + f.name + "[" + zshDesc(f.help) + "]"
			if f.value != "" {
				spec += ":" + strings.ToLower(f.value) + ":"
				if len(f.choices) > 0 {
					spec += "(" + strings.Join(f.choices, " ") + ")"
				} else {
					spec += " "
				}
			}
			fmt.Fprintf(b, " \\\n\t\t\t%s", shellQuote(spec))
		}
		for _, h := range []string{"-h", "--help"} {
			fmt.Fprintf(b, " \\\n\t\t\t%s", shellQuote(h+"["+zshDesc(msgFlagHelp)+"]"))
		}
		switch {
		case len(c.choices) > 0:
			fmt.Fprintf(b, " \\\n\t\t\t%s", shellQuote("1:"+zshDesc(c.argHelp)+":("+strings.Join(c.choices, " ")+")"))
		case c.maxArgs < 0:
			fmt.Fprintf(b, " \\\n\t\t\t%s", shellQuote("*:"+zshDesc(c.argHelp)+": "))
		case c.maxArgs > 0:
			fmt.Fprintf(b, " \\\n\t\t\t%s", shellQuote("1:"+zshDesc(c.argHelp)+": "))
		}
		b.WriteString("\n\t\t;;\n")
	}
	b.WriteString("\tesac\n}\n_sona \"$@\"\n")
}

func fishCompletion(b *strings.Builder) {
	b.WriteString("# fish completion for sona, generated by `sona completion fish`.\n")
	b.WriteString("function __sona_command\n\tset -l words (commandline -opc)\n\ttest (count $words) -ge 2; and test $words[2] = $argv[1]\nend\n")
	b.WriteString("complete -c sona -f\n")
	for _, c := range commands {
		fmt.Fprintf(b, "complete -c sona -n 'test (count (commandline -opc)) -eq 1' -a %s -d %s\n", c.name, fishQuote(c.summary))
	}
	for _, c := range commands {
		cond := fishQuote("__sona_command " + c.name)
		if len(c.choices) > 0 {
			fmt.Fprintf(b, "complete -c sona -n %s -a %s\n", cond, fishQuote(strings.Join(c.choices, " ")))
		}
		for _, f := range c.flags {
			fmt.Fprintf(b, "complete -c sona -n %s -l %s", cond, f.name)
			if f.value != "" {
				b.WriteString(" -x")
				if len(f.choices) > 0 {
					fmt.Fprintf(b, " -a %s", fishQuote(strings.Join(f.choices, " ")))
				}
			}
			fmt.Fprintf(b, " -d %s\n", fishQuote(f.help))
		}
		fmt.Fprintf(b, "complete -c sona -n %s -s h -l help -d %s\n", cond, fishQuote(msgFlagHelp))
	}
}
