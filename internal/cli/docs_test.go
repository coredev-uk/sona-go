func script(t *testing.T, shell string) string {
	t.Helper()
	var b bytes.Buffer
	if err := writeCompletion(&b, nil, shell); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "sona."+shell)
	if err := os.WriteFile(path, b.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

// bash completes command names, a command's arguments and options, and
// option values, from the table.
func TestBashCompletion(t *testing.T) {
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Skip("bash not available")
	}
	path := script(t, "bash")
	complete := func(words ...string) []string {
		t.Helper()
		// The word being completed is the last one.
		var arr strings.Builder
		for _, w := range words {
			arr.WriteString(shellQuote(w) + " ")
		}
		cmd := exec.Command(bash, "--norc", "--noprofile", "-c",
			`source "$1"; COMP_WORDS=(`+arr.String()+`); COMP_CWORD=$((${#COMP_WORDS[@]}-1)); _sona; printf '%s\n' "${COMPREPLY[@]}"`,
			"bash", path)
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("bash: %v\n%s", err, out)
		}
		return strings.Fields(string(out))
	}
	for _, tc := range []struct {
		words []string
		want  string
	}{
		{[]string{"sona", "pr"}, "prev private"},
		{[]string{"sona", "st"}, "status"},
		{[]string{"sona", "status", "--f"}, "--follow --format"},
		{[]string{"sona", "like", ""}, "on off toggle status --json --help"},
		{[]string{"sona", "search", "--type", "a"}, "album artist"},
		{[]string{"sona", "search", "--limit", ""}, ""},
		{[]string{"sona", "completion", "z"}, "zsh"},
		{[]string{"sona", "help", "vol"}, "volume"},
	} {
		if got := strings.Join(complete(tc.words...), " "); got != tc.want {
			t.Errorf("complete %q = %q, want %q", tc.words, got, tc.want)
		}
	}
}

// The zsh and fish scripts parse in their shells (where installed).
func TestZshFishCompletionSyntax(t *testing.T) {
	ran := false
	if zsh, err := exec.LookPath("zsh"); err == nil {
		ran = true
		if out, err := exec.Command(zsh, "-n", script(t, "zsh")).CombinedOutput(); err != nil {
			t.Errorf("zsh -n: %v\n%s", err, out)
		}
	}
	if fish, err := exec.LookPath("fish"); err == nil {
		ran = true
		if out, err := exec.Command(fish, "--no-execute", script(t, "fish")).CombinedOutput(); err != nil {
			t.Errorf("fish --no-execute: %v\n%s", err, out)
		}
	}
	if !ran {
		t.Skip("neither zsh nor fish available")
	}
}

// The manual page lists every command and option and passes a roff
// linter (where installed).
func TestManPage(t *testing.T) {
	var b bytes.Buffer
	if err := writeMan(&b, nil, "1.2.3"); err != nil {
		t.Fatal(err)
	}
	page := b.String()
	if !strings.HasPrefix(page, `.TH SONA 1 "" "Sona 1.2.3" `) {
		t.Errorf("no title line:\n%.80s", page)
	}
	for _, c := range commands {
		if !strings.Contains(page, `.B "sona `+roff(c.name)) {
			t.Errorf("command %s missing", c.name)
		}
		for _, f := range c.flags {
			if !strings.Contains(page, roff("--"+f.name)) {
				t.Errorf("%s: option --%s missing", c.name, f.name)
			}
		}
	}
	requests := []string{".TH ", ".SH ", ".TP", ".B ", ".I ", ".RS", ".RE", ".PP", ".nf", ".fi"}
	for _, line := range strings.Split(page, "\n") {
		if strings.HasPrefix(line, "'") {
			t.Errorf("line would read as a request: %q", line)
		}
		if strings.HasPrefix(line, ".") && !slices.ContainsFunc(requests, func(r string) bool { return strings.HasPrefix(line, r) }) {
			t.Errorf("unexpected request: %q", line)
		}
	}
	if mandoc, err := exec.LookPath("mandoc"); err == nil {
		cmd := exec.Command(mandoc, "-T", "lint", "-W", "warning")
		cmd.Stdin = strings.NewReader(page)
		out, _ := cmd.CombinedOutput()
		// The page has no date: it is generated by the binary, which
		// knows its version but not when it was built.
		for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			if line != "" && !strings.Contains(line, "missing date") {
				t.Errorf("mandoc -T lint: %s", line)
			}
		}
	}
}

func TestHelp(t *testing.T) {
	var b bytes.Buffer
	if err := writeOverview(&b, nil); err != nil {
		t.Fatal(err)
	}
	for _, c := range commands {
		if !strings.Contains(b.String(), "\n  "+c.name+" ") {
			t.Errorf("overview misses %s", c.name)
		}
	}
	b.Reset()
	if err := writeHelp(&b, nil, lookup("search")); err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"usage: sona search <term>… [options]", "--type KIND", "song, album", "--limit N", "-h, --help", "Exit status:"} {
		if !strings.Contains(b.String(), want) {
			t.Errorf("search help misses %q:\n%s", want, b.String())
		}
	}
	for _, line := range strings.Split(b.String(), "\n") {
		if len([]rune(line)) > helpWidth {
			t.Errorf("line longer than %d: %q", helpWidth, line)
		}
	}
}
